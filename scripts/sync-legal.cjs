// Copies the in-app legal text (src/features/legal/legalContent.ts) into the backend, which
// serves the same pages publicly for the Play Console privacy policy and account deletion URLs.
//   node scripts/sync-legal.cjs          write dfbackend/src/legal/legal-content.ts
//   node scripts/sync-legal.cjs --check  fail if the backend copy is out of date
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const target = path.join(root, 'dfbackend', 'src', 'legal', 'legal-content.ts');

function load(file, modules = {}) {
  const exports = {};
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const code = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  vm.runInNewContext(code, { exports, require: (name) => modules[name] });
  return exports;
}

function legalSource() {
  const constants = load('src/utils/constants.ts');
  const legal = load('src/features/legal/legalContent.ts', { '@/utils/constants': constants });
  const content = {
    supportEmail: constants.SUPPORT_EMAIL,
    minimumAge: legal.MINIMUM_AGE,
    privacy: legal.privacyPolicy,
    terms: legal.termsOfUse,
    deletion: legal.accountDeletion,
  };
  return `// Generated by scripts/sync-legal.cjs in the mobile app from src/features/legal/legalContent.ts.
// Do not edit here: change the app's text and run \`npm run legal:sync\`.
export const LEGAL_CONTENT = ${JSON.stringify(content, null, 2)} as const;
`;
}

function isCurrent() {
  try {
    return fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') === legalSource();
  } catch {
    return false;
  }
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!isCurrent()) {
      console.error('dfbackend/src/legal/legal-content.ts is out of date. Run npm run legal:sync.');
      process.exitCode = 1;
    } else console.log('Backend legal pages match the app.');
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, legalSource());
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}
module.exports = { legalSource, isCurrent, target };
